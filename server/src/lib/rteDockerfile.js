/******************************************************************/
/*                                                                */
/*  An RTE image's build : what a builder is handed to build it   */
/*  (lib/rteImages.js gives the definition). The Dockerfile, on   */
/*  the published RTE layers as ansibleforms/rte's examples do, and the files  */
/*  it copies : the python packages as a requirements.txt, the    */
/*  collections as a requirements.yml - never put on a RUN line,  */
/*  so no value of the definition is ever run by a shell. Its OS  */
/*  packages are names only (normalizeImage refuses any other).   */
/*                                                                */
/******************************************************************/
import YAML from "yaml";

// ===========================================================================
// THE BASES AND THEIR PYTHON
// ===========================================================================

// where the published RTE layers are (ansibleforms/rte's publish.yml)
export const BASE_REGISTRY = "ghcr.io/ansibleforms";

// the uv that brings an image's python : the one rte-core is built with
// (rte-core/Dockerfile of ansibleforms/rte, whose CI keeps the two the same)
export const UV_IMAGE = "ghcr.io/astral-sh/uv:0.13.10@sha256:a3ea1357342c1a4bf9a0c53a3deb1b55379aefa037338d8113d5771efa01774f";

// the python the published rte-core runs (ansibleforms/rte's rte-core/Dockerfile PYTHON_VERSION) ; a
// runtime environment that names none gets the newest instead (DEFAULT_PYTHON)
export const CORE_PYTHON = "3.14";

// the distribution every RTE layer is built on (ansibleforms/rte's rte-base : node:26-trixie-slim)
export const RTE_OS = "Debian 13 (trixie)";

// the pythons an image may run
export const PYTHONS = ["3.11", "3.12", "3.13", "3.14", "3.15"];
// the python a runtime environment gets when it says none : the newest, as everything else that is
// not pinned (ansible-core the newest release that runs on it, collections and packages their latest)
export const DEFAULT_PYTHON = PYTHONS[PYTHONS.length - 1];

// the pythons each ansible-core release runs on as a control node (its support matrix)
export const ANSIBLE_CORE_PYTHONS = {
  "2.15": ["3.9", "3.10", "3.11"],
  "2.16": ["3.10", "3.11", "3.12"],
  "2.17": ["3.10", "3.11", "3.12"],
  "2.18": ["3.11", "3.12", "3.13"],
  "2.19": ["3.11", "3.12", "3.13"],
  "2.20": ["3.12", "3.13", "3.14"],
  "2.21": ["3.12", "3.13", "3.14"],
  // 2.22 : the three latest pythons, 3.15 added and 3.12 dropped (its roadmap)
  "2.22": ["3.13", "3.14", "3.15"],
};

// the ansible.cfg of the published layers (server/ansible.cfg, a test keeps the two the same) :
// rte-base, which every image starts from, has none of its own
// What the collections themselves need, as ansible-builder reads it : each installed collection's
// meta/execution-environment.yml (dependencies.python and dependencies.system, a file of the
// collection or a list), else its requirements.txt and bindep.txt at its root. Run once the
// collections are installed : it writes the python requirements (ansible, ansible-core and
// ansible-base left out, the definition's ansible-core stays) and the bindep lines, each under a
// comment naming its collection, for the Dockerfile's next steps.
export const COLLECTION_DEPS_PY = `# The python and system packages the installed collections need, gathered for the build.
# Generated by AnsibleForms : run once, then removed.
import os, re, sys

ROOT = os.path.join(sys.argv[1], "ansible_collections")
OUT = sys.argv[2]
# the definition's ansible-core stays : a collection never brings its own
SKIP = re.compile(r"^(ansible|ansible-core|ansible-base)([^A-Za-z0-9._-]|$)", re.I)

try:
    import yaml
except Exception:
    yaml = None


def lines_of(path):
    try:
        with open(path, encoding="utf-8") as f:
            return [l.rstrip("\\n") for l in f]
    except OSError:
        return []


def entries(col, value, default):
    # a list of lines, or a file of the collection, or the default file
    if isinstance(value, list):
        return [str(v) for v in value]
    if isinstance(value, str) and value.strip():
        return lines_of(os.path.join(col, value.strip()))
    return lines_of(os.path.join(col, default))


python, system = [], []
if os.path.isdir(ROOT):
    for ns in sorted(os.listdir(ROOT)):
        for name in sorted(os.listdir(os.path.join(ROOT, ns))):
            col = os.path.join(ROOT, ns, name)
            if not os.path.isdir(col):
                continue
            deps = {}
            for meta in ("execution-environment.yml", "execution-environment.yaml"):
                path = os.path.join(col, "meta", meta)
                if yaml and os.path.isfile(path):
                    with open(path, encoding="utf-8") as f:
                        deps = ((yaml.safe_load(f) or {}).get("dependencies") or {})
                    break
            req = [l for l in entries(col, deps.get("python"), "requirements.txt") if l.strip() and not l.strip().startswith("#")]
            req = [l for l in req if not SKIP.match(l.strip())]
            bind = [l for l in entries(col, deps.get("system"), "bindep.txt") if l.strip() and not l.strip().startswith("#")]
            if req:
                python += ["# " + ns + "." + name] + req
            if bind:
                system += ["# " + ns + "." + name] + bind

os.makedirs(OUT, exist_ok=True)
with open(os.path.join(OUT, "requirements.txt"), "w", encoding="utf-8") as f:
    f.write("\\n".join(python) + ("\\n" if python else ""))
with open(os.path.join(OUT, "bindep.txt"), "w", encoding="utf-8") as f:
    f.write("\\n".join(system) + ("\\n" if system else ""))
print("Collection dependencies: %d python, %d system" % (sum(1 for l in python if not l.startswith("#")), sum(1 for l in system if not l.startswith("#"))))
`;

export const ANSIBLE_CFG = `[defaults]
callback_result_format = yaml
COLLECTIONS_PATH=/usr/share/ansible/collections/ansible_collections:/etc/ansible/collections/ansible_collections
`;

/**
 * The python an image runs on : its own, the default one when it names none.
 *
 * Args:
 *   image (object): the definition.
 *
 * Returns:
 *   string: the python (3.13).
 */
export const pythonOf = (image) => String(image.python || DEFAULT_PYTHON);

/**
 * The newest ansible-core release that runs on a python.
 *
 * Args:
 *   python (string): the python.
 *
 * Returns:
 *   string: the release (2.22) ; '' when none does.
 */
export function newestAnsibleCore(python) {
  return (
    Object.keys(ANSIBLE_CORE_PYTHONS)
      .filter((r) => ANSIBLE_CORE_PYTHONS[r].includes(python))
      .sort((a, b) => b.localeCompare(a, undefined, { numeric: true }))[0] || ""
  );
}

/**
 * The pip requirement of an ansible-core : a release (2.22) is its latest patch (~=2.22.0), a
 * version (2.22.1) that one exactly.
 *
 * Args:
 *   version (string): the release or the version.
 *
 * Returns:
 *   string: the requirement (ansible-core~=2.22.0, ansible-core==2.22.1).
 */
export function ansibleCoreRequirement(version) {
  const v = String(version || "");
  return /^\d+\.\d+$/.test(v) ? `ansible-core~=${v}.0` : `ansible-core==${v}`;
}

/**
 * The versions an RTE image is made of, for the Designer's dropdowns : the operating system, the
 * pythons, the one an image gets by default, and the ansible-core releases with the pythons each
 * runs on.
 *
 * Returns:
 *   object: { os, pythons, defaultPython, ansibleCore: { release: [pythons] } }.
 */
export const versionsOf = () => ({ os: RTE_OS, pythons: PYTHONS, defaultPython: DEFAULT_PYTHON, ansibleCore: ANSIBLE_CORE_PYTHONS });

/**
 * Why an ansible-core cannot run on a python, when it cannot.
 *
 * Args:
 *   ansibleCore (string): the ansible-core version (2.18.12).
 *   python (string): the python (3.13).
 *
 * Returns:
 *   string: why ; '' when it fits, or when the release is not one the table knows (a newer one).
 */
export function ansibleCoreMisfit(ansibleCore, python) {
  const release = String(ansibleCore || "").match(/^(\d+\.\d+)/)?.[1];
  const pythons = release && ANSIBLE_CORE_PYTHONS[release];
  if (!pythons || pythons.includes(python)) return "";
  return `ansible-core ${release} runs on python ${pythons.join(", ")}, not ${python}`;
}

// ===========================================================================
// THE TAGS
// ===========================================================================

/**
 * The tag of the published RTE layers a build starts from : the app's release (7.8.0) ; its major
 * (7) for a version that is no release (a development build).
 *
 * Args:
 *   appVersion (string): the app's version.
 *
 * Returns:
 *   string: the tag.
 */
export function baseTagOf(appVersion) {
  const v = String(appVersion || "");
  if (/^\d+\.\d+\.\d+$/.test(v)) return v;
  return v.match(/^(\d+)/)?.[1] || "7";
}

/**
 * The tag an image is pushed with : the app's release for tag: app, else its own.
 *
 * Args:
 *   image (object): the definition.
 *   appVersion (string): the app's version.
 *
 * Returns:
 *   string: the tag.
 */
export const imageTagOf = (image, appVersion) => {
  const tag = image.registry?.tag ?? image.tag;
  return !tag || tag === "app" ? baseTagOf(appVersion) : String(tag);
};

/**
 * The full reference an image is pushed to : the registry's host, the repository and the tag.
 *
 * Args:
 *   image (object): the definition.
 *   registryUrl (string): the registry credential's address (https://registry.example.com).
 *   appVersion (string): the app's version.
 *
 * Returns:
 *   string: registry.example.com/af/rte-vmware:7.8.0 ; the repository and tag alone without a
 *   registry.
 */
export function imageRefOf(image, registryUrl, appVersion) {
  const host = String(registryUrl || "")
    .replace(/^[a-z]+:\/\//i, "")
    .replace(/\/+$/, "");
  const repository = image.registry?.path || image.name;
  return `${host ? `${host}/` : ""}${repository}:${imageTagOf(image, appVersion)}`;
}

