/**
 * The python packages as a requirements.txt : one line each.
 *
 * Args:
 *   image (object): the definition.
 *
 * Returns:
 *   string: the file ('' without any).
 */
export function requirementsTxt(image) {
  const lines = (image.python_packages || []).map((p) => String(p).trim()).filter(Boolean);
  return lines.length ? `${lines.join("\n")}\n` : "";
}

/**
 * The collections as an ansible-galaxy requirements.yml.
 *
 * Args:
 *   image (object): the definition.
 *
 * Returns:
 *   string: the file ('' without any).
 */
export function requirementsYml(image) {
  const collections = (image.ansible_collections || []).map((c) => (typeof c === "string" ? { name: c } : { ...c }));
  return collections.length ? YAML.stringify({ collections }) : "";
}

/**
 * The Dockerfile of an image, built from scratch on the one layer it cannot do without :
 * rte-base, Debian with node and the AnsibleForms runner of the app's release, no python and no
 * ansible. On it, all from the definition : its OS packages, its python (by uv), its ansible-core,
 * its python packages and its collections, its venv given to node, run as node.
 *
 * Args:
 *   image (object): the definition (normalizeImage's).
 *   appVersion (string): the app's version (the layer's tag).
 *
 * Returns:
 *   string: the Dockerfile.
 */
export function dockerfileOf(image, appVersion) {
  const lines = [];
  const add = (...l) => lines.push(...l);
  add(`# The runtime environment '${image.name}', generated by AnsibleForms from its definition.`, `# Edit the definition, not this file : it is made again for every build.`);
  add(`FROM ${UV_IMAGE} AS uv`);
  add(`FROM ${BASE_REGISTRY}/ansibleforms-rte-base:${baseTagOf(appVersion)}`, "", "USER root");
  if (image.description) add(`LABEL org.opencontainers.image.title=${JSON.stringify(image.name)} org.opencontainers.image.description=${JSON.stringify(String(image.description))}`);
  const os = image.os_packages || [];
  if (os.length) {
    add("", "# its OS packages", "RUN apt-get update \\", ` && apt-get install -y --no-install-recommends ${os.join(" ")} \\`, " && rm -rf /var/lib/apt/lists/*");
  }
  add(
      "",
      `# python ${image.python}, brought by uv, in the venv the RTE runs`,
      "ENV UV_PYTHON_INSTALL_DIR=/opt/python",
      `RUN --mount=from=uv,source=/uv,target=/usr/local/bin/uv \\`,
      `    uv python install "${image.python}" \\`,
      ` && uv venv --seed --python "${image.python}" /venv \\`,
      " && chmod -R a+rX /opt/python /venv",
      'ENV PATH="/venv/bin:$PATH"',
      "COPY ansible.cfg /etc/ansible/ansible.cfg",
    );
  add("", "# its ansible-core", `RUN pip install --no-cache-dir "${ansibleCoreRequirement(image.ansible_core)}"`);
  if (requirementsTxt(image)) add("", "# its python packages", "COPY requirements.txt /tmp/rte-requirements.txt", "RUN pip install --no-cache-dir -r /tmp/rte-requirements.txt && rm /tmp/rte-requirements.txt");
  if (requirementsYml(image)) {
    add(
      "",
      "# its collections, where every RTE finds them",
      "COPY requirements.yml /tmp/rte-collections.yml",
      "RUN ansible-galaxy collection install -r /tmp/rte-collections.yml -p /usr/share/ansible/collections && rm /tmp/rte-collections.yml",
    );
    // what the collections need themselves, as ansible-builder installs it : their python
    // requirements by pip, their bindep.txt by bindep (only the packages missing on this
    // Debian), then bindep removed again
    add(
      "",
      "# what its collections need themselves : their requirements.txt and bindep.txt",
      "COPY collection-deps.py /tmp/rte-collection-deps.py",
      "RUN python /tmp/rte-collection-deps.py /usr/share/ansible/collections /tmp/rte-deps \\",
      ' && if [ -s /tmp/rte-deps/requirements.txt ]; then pip install --no-cache-dir -r /tmp/rte-deps/requirements.txt; fi \\',
      ' && if [ -s /tmp/rte-deps/bindep.txt ]; then \\',
      "      pip install --no-cache-dir bindep \\",
      '      && pkgs="$(bindep -b -f /tmp/rte-deps/bindep.txt || true)" \\',
      "      && pip uninstall -y bindep \\",
      '      && if [ -n "$pkgs" ]; then apt-get update && apt-get install -y --no-install-recommends $pkgs && rm -rf /var/lib/apt/lists/*; fi; \\',
      "    fi \\",
      " && rm -rf /tmp/rte-deps /tmp/rte-collection-deps.py",
    );
  }
  add("", "# the venv and the collections belong to node, which the RTE runs as", "RUN mkdir -p /usr/share/ansible/collections && chown -R node:node /venv /home/node /usr/share/ansible/collections", "USER node", "");
  return lines.join("\n");
}

/**
 * Everything a builder needs to build an image : its Dockerfile and the files it copies.
 *
 * Args:
 *   image (object): the definition (normalizeImage's).
 *   appVersion (string): the app's version.
 *
 * Returns:
 *   object: { file name: its text }.
 */
export function buildContextOf(image, appVersion) {
  const files = { Dockerfile: dockerfileOf(image, appVersion) };
  files["ansible.cfg"] = ANSIBLE_CFG;
  const txt = requirementsTxt(image);
  if (txt) files["requirements.txt"] = txt;
  const yml = requirementsYml(image);
  if (yml) {
    files["requirements.yml"] = yml;
    // the collections' own dependencies, gathered once they are installed
    files["collection-deps.py"] = COLLECTION_DEPS_PY;
  }
  return files;
}

export default { newestAnsibleCore, dockerfileOf, buildContextOf, imageRefOf, imageTagOf, baseTagOf, ansibleCoreMisfit, pythonOf };
